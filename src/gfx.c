#define FONT_W      5
#define FONT_H      7
#define FONT_GAP    1       /* 字距（列数） */

void gfx_text(int x, int y, const char *s, uint16_t color, int scale)
{
    int w, h;
    uint16_t *buf;
    int cx = x;

    if (!s || scale < 1)
        return;
    if (scale > 4)
        scale = 4;      /* 防止误传大值把整屏写满 */

    buf = g_buf(&w, &h);
    if (!buf)
        return;

    for (; *s; s++)
    {
        unsigned char c = (unsigned char)*s;
        const uint8_t *glyph;

        if (c >= 'a' && c <= 'z')
            c = (unsigned char)(c - 'a' + 'A');

        glyph = (c >= 0x20u && c <= 0x5Au) ? s_font5x7[c - 0x20u] : s_font5x7[0];

        for (int col = 0; col < FONT_W; col++)
        {
            uint8_t bits = glyph[col];

            if (!bits)
                continue;

            for (int row = 0; row < FONT_H; row++)
            {
                if (!(bits & (1u << row)))
                    continue;

                /* 一个点放大成 scale × scale 的方块 */
                for (int dy = 0; dy < scale; dy++)
                {
                    int py = y + row * scale + dy;
                    uint16_t *line;

                    if (py < 0 || py >= h)
                        continue;

                    line = buf + (rt_uint32_t)py * (rt_uint32_t)w;

                    for (int dx = 0; dx < scale; dx++)
                    {
                        int px = cx + col * scale + dx;

                        if (px >= 0 && px < w)
                            line[px] = color;
                    }
                }
            }
        }

        cx += (FONT_W + FONT_GAP) * scale;
    }
}

int gfx_text_width(const char *s, int scale)
{
    int n = 0;

    if (!s || scale < 1)
        return 0;

    while (*s++)
        n++;

    /* 末字符不留字距 */
    return n ? (n * (FONT_W + FONT_GAP) - FONT_GAP) * scale : 0;
}
